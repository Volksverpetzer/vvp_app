/**
 * Reads the German fastlane changelog for the current versionCode, copies it
 * to the English Android path (unless a translation already exists there),
 * and regenerates src/constants/Changelog.ts.
 *
 * Usage: pnpm prepare:changelog
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const { version, versionCode } = pkg;

const dePath = resolve(
  root,
  `fastlane/metadata/android/de-DE/changelogs/${versionCode}.txt`,
);
const enPath = resolve(
  root,
  `fastlane/metadata/android/en-US/changelogs/${versionCode}.txt`,
);
const outPath = resolve(root, "src/constants/Changelog.ts");

let notes = "";

if (!existsSync(dePath)) {
  console.error(
    `✗ No changelog found at fastlane/metadata/android/de-DE/changelogs/${versionCode}.txt`,
  );
  console.error(
    "  Create this file with release notes, then re-run this script.",
  );
  process.exit(1);
}

notes = readFileSync(dePath, "utf8").trim();
if (existsSync(enPath)) {
  console.log(
    `✓ Kept existing en-US changelog for v${version} (${versionCode})`,
  );
} else {
  copyFileSync(dePath, enPath);
  console.log(
    `✓ Copied de-DE → en-US changelog for v${version} (${versionCode}) — consider translating it`,
  );
}

const content = `// Auto-generated by scripts/prepare-changelog.mjs — do not edit manually
const Changelog = {
  version: "${version}",
  versionCode: ${versionCode},
  notes: ${JSON.stringify(notes)},
};

export default Changelog;
`;

writeFileSync(outPath, content, "utf8");
console.log("✓ Generated src/constants/Changelog.ts");
